"""Regenerate the static localization map after editing MainView.xaml. No runtime XML/reflection."""

import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

app = Path(__file__).resolve().parents[1] / "App"
entries = []
for element in ET.parse(app / "MainView.xaml").iter():
    for prop, text in element.attrib.items():
        if prop not in (
            "Text",
            "Content",
            "Header",
            "PlaceholderText",
            "AutomationProperties.Name",
            "ToolTipService.ToolTip",
        ) or not re.search("[\u4e00-\u9fff]", text):
            continue
        name = element.get("{http://schemas.microsoft.com/winfx/2006/xaml}Name")
        if not name:
            raise ValueError(f"Localized {element.tag} requires x:Name: {text}")
        entries.append((name, prop, text))
result = "// Generated by tools/Update-ViewText.py; edit MainView.xaml, then regenerate.\nnamespace VideoConverter;\n\ninternal static class ViewText\n{\n    internal static readonly (string Name, string Property, string Original)[] Entries =\n    [\n"
for entry in entries:
    result += (
        "        ("
        + ", ".join(json.dumps(s, ensure_ascii=False) for s in entry)
        + "),\n"
    )
result += "    ];\n}\n"
target = app / "ViewText.g.cs"
if "--check" in sys.argv:
    if not target.exists() or target.read_text(encoding="utf-8") != result:
        raise SystemExit(
            "Localization map is stale; run python tools/Update-ViewText.py"
        )
else:
    target.write_text(result, encoding="utf-8")
print(
    f"Checked {len(entries)} static view localization entries."
    if "--check" in sys.argv
    else f"Generated {len(entries)} static view localization entries."
)
